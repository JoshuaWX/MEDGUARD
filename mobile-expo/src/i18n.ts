const STORAGE_KEY = 'mg_lang';

type I18nContextValue = {
  lang: LangCode;
  setLang: (code: LangCode) => Promise<void>;
  t: (key: keyof typeof messages.en | string, params?: Record<string, string | number>) => string;
  ready: boolean;
};

const I18nContext = createContext<I18nContextValue | null>(null);

export const I18nProvider: React.FC<React.PropsWithChildren> = ({ children }) => {
  const [lang, setLangState] = useState<LangCode>('en');
  // Start ready immediately with default language to avoid loading flash
  const [ready, setReady] = useState(true);

  useEffect(() => {
    let cancelled = false;
    (async () => {
      try {
        const saved = await AsyncStorage.getItem(STORAGE_KEY);
        if (!cancelled && saved && (saved in messages)) {
          setLangState(saved as LangCode);
        }
      } catch {
        // ignore
      }
    })();
    return () => {
      cancelled = true;
    };
  }, []);

  const setLang = useCallback(async (code: LangCode) => {
    if (!(code in messages)) return;
    setLangState(code);
    try {
      await AsyncStorage.setItem(STORAGE_KEY, code);
    } catch {
      // ignore
    }
  }, []);

  const t = useCallback(
    (key: string, params?: Record<string, string | number>) => {
      const raw = messages[lang]?.[key] || messages.en[key] || key;
      if (!params) return raw;
      return Object.keys(params).reduce((acc, paramKey) => {
        const v = String(params[paramKey]);
        return acc.replaceAll(`{${paramKey}}`, v);
      }, raw);
    },
    [lang]
  );

  const value = useMemo<I18nContextValue>(() => ({ lang, setLang, t, ready }), [lang, setLang, t, ready]);

  return React.createElement(I18nContext.Provider, { value }, children);
};

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error('useI18n must be used within <I18nProvider>.');
  return ctx;
}
